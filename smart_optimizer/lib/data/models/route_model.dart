class RouteModel {
  final String title;
  final String transport;
  final int duration;
  final int cost;
  final String comfort;
  final String crowd;
  final double score;

  RouteModel({
    required this.title,
    required this.transport,
    required this.duration,
    required this.cost,
    required this.comfort,
    required this.crowd,
    required this.score,
  });
}